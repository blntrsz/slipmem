const jsonRequest = (
  path: string,
  method: string,
  body: unknown,
  headers: Record<string, string> = {},
) =>
  new Request(`http://localhost${path}`, {
    method,
    headers: {
      "content-type": "application/json",
      accept: "application/json, text/event-stream",
      ...headers,
    },
    body: JSON.stringify(body),
  })

const initializeMcp = async (api: ReturnType<typeof makeApiHandler>) => {
  const response = await api.handler(
    jsonRequest("/mcp", "POST", {
      jsonrpc: "2.0",
      id: 1,
      method: "initialize",
      params: {
        protocolVersion: "2025-11-25",
        capabilities: {},
        clientInfo: { name: "slipmem-http-chat-test", version: "0.0.0" },
      },
    }),
  )
  expect(response.status).toBe(200)
  const sessionId = response.headers.get("mcp-session-id")
  expect(sessionId).toBeTruthy()
  await response.text()
  return sessionId!
}

const callTool = async (
  api: ReturnType<typeof makeApiHandler>,
  sessionId: string,
  name: string,
  args: unknown,
) => {
  const response = await api.handler(
    jsonRequest(
      "/mcp",
      "POST",
      {
        jsonrpc: "2.0",
        id: 2,
        method: "tools/call",
        params: { name, arguments: args },
      },
      {
        "mcp-session-id": sessionId,
        "mcp-protocol-version": "2025-11-25",
      },
    ),
  )
  expect(response.status).toBe(200)
  return (await response.json()) as {
    readonly result: { readonly structuredContent?: unknown }
  }
}

const fakeChat = (): PrimaryChatModel => ({
  model: "http-fixture",
  label: "http-fixture (local)",
  egress: "local",
  chat: (() => Effect.die("the fixture does not call chat")) as unknown as
    PrimaryChatModel["chat"],
})

test("HTTP MCP requires the same primary chat model as stdio", () => {
  const root = "/tmp/slipmem-required-chat-does-not-need-to-exist"

  // The production serve resolvers require a primary chat model. HTTP must not
  // become a no-model escape hatch beside stdio.
  expect(() => makeServerLayer({ root, env: {} })).toThrow(
    "requires a primary chat model",
  )
  expect(() => makeMcpHttp({ root, env: {} })).toThrow(
    "requires a primary chat model",
  )

  // A partial chat configuration is a startup error on both transports, not a
  // silent fallback to keyword recall or a different provider.
  const partial = { root, env: { SLIPMEM_CHAT_PROVIDER: "openai-compatible" } }
  expect(() => makeServerLayer(partial)).toThrow("SLIPMEM_CHAT_MODEL")
  expect(() => makeMcpHttp(partial)).toThrow("SLIPMEM_CHAT_MODEL")

  // Programmatic hosts and tests can still inject an explicit disabled runtime,
  // so the HTTP Markdown/approval contract does not need a live provider.
  expect(() =>
    makeMcpHttp({ root, env: {}, automaticMemory: { enabled: false } }),
  ).not.toThrow()
})

test("HTTP MCP accepts an injected fixture runtime and drains a raw write", async () => {
  const directory = await mkdtemp(join(tmpdir(), "slipmem-http-chat-"))
  const root = join(directory, ".slipmem")
  const cacheDir = join(directory, "cache")
  const now = () => Date.UTC(2026, 10, 22, 12, 0, 0)
  const providerCalls: string[] = []

  try {
    await Effect.runPromise(initializeNoteRoot(root))
    const repository = await Effect.runPromise(
      makeMarkdownNoteRepository({ root, now }),
    )
    const source = await Effect.runPromise(
      repository.create({
        type: "fleeting",
        title: "HTTP raw source",
        content: "A raw source that the injected maintenance fixture consumes.",
        tags: ["http-fixture"],
        provenance: { source: "mcp", actor: "test" },
      }),
    )

    const provider: AutomaticMemoryProvider = {
      maintenance: (request) => {
        providerCalls.push(
          request.sources.map((item) => item.id).join(","),
        )
        return Effect.succeed({
          operations: [
            {
              operation: "create",
              title: "HTTP fixture permanent",
              content: "Generated by the injected HTTP maintenance fixture.",
              tags: ["http-fixture"],
              sourceIds: request.sources.map((item) => item.id),
            },
          ],
        })
      },
      chat: fakeChat(),
      label: "http-fixture (local)",
      egress: "local",
    }

    const automaticMemory: AutomaticMemoryRuntime = {
      enabled: true,
      provider,
      watch: false,
      revisionGate: false,
      lease: { pollMs: 10 },
      report: () => undefined,
    }

    const api = makeApiHandler(root, {
      disableLogger: true,
      cacheDir,
      now,
      extraRoutes: makeMcpHttp({
        root,
        cacheDir,
        now,
        automaticMemory,
      }),
    })

    try {
      // Building the handler mounts the MCP registrations, which fork the
      // event-driven maintenance fiber and enqueue one startup recovery pass.
      const sessionId = await initializeMcp(api)

      let permanents: ReadonlyArray<{ id: string; title: string }> = []
      const deadline = Date.now() + 5_000
      while (Date.now() < deadline) {
        const listed = await callTool(api, sessionId, "list_permanent_notes", {})
        permanents = (
          listed.result.structuredContent as {
            readonly notes: ReadonlyArray<{ id: string; title: string }>
          }
        ).notes
        if (permanents.some((note) => note.title === "HTTP fixture permanent")) {
          break
        }
        await Bun.sleep(25)
      }

      expect(permanents.some((note) => note.title === "HTTP fixture permanent")).toBe(
        true,
      )
      expect(providerCalls).toContain(source.id)

      const scan = await Effect.runPromise(repository.scan())
      expect(scan.notes.some((note) => note.id === source.id)).toBe(true)
      expect(
        scan.notes.filter((note) => note.metadata.type === "permanent"),
      ).toHaveLength(1)
    } finally {
      await api.dispose()
    }
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
}, 30_000)
